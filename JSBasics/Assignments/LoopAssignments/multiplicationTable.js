/*3.Multiplication Table
Problem Statement:
Write a JavaScript program that accepts a number and prints its multiplication table from 1 to 10.*/
//2 * 1 = 2
let n=7;
for(let i=1;i<=10;i++)
{
    let mul=n*i;
    console.log(`${n} * ${i} =${mul} `)
}

